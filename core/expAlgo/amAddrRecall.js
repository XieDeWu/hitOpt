/* ══════════════════════════════════════════════════════════════════════════════════════
 * 算法：**区间唤起**（`core/expAlgo/amAddrRecall.js`）
 *
 *   id `am-addr-recall` ｜ 名字「区间唤起」｜ 版本 `v1`
 *
 * ── 它是什么（用户 2026-09-20 定版：算法组合管线）─────────────────────────────────
 *   管线里的一级：把 B 区正文里**"真发出去过的连续区间"**按最长匹配换成 `<AMxxxx/>`
 *   —— 它够得到块级那一层**天生够不到**的东西：不在任何配对标签里的裸正文
 *   （盘上实测：B 区多出来的 74,622 字里指针只有 719 字，裸正文 73,010 字，
 *     其中"上一轮已逐字发过"的连续段有 11 段 / 69,065 字）。
 *
 *   ⚠ 它**只做一层**：遇到指针就整段跳过 ⇒ 结果里绝不会出现"指针里套指针"（用户指令 D）。
 *
 * ── 为什么这个文件里没有算法本体（**如实写，不冒充模块化**）────────────────────────
 *   本体是客户端 `_abSplit` 里那一段（`_amAddrRecall` ＋第二次 `B.map`），依赖**跨轮台账**：
 *   `_amAddrPool`（区间地址台账，逐聊天从 localStorage 装回来）、`AM_ADDR_MIN`（最短引用长度）、
 *   `_amAddrStat`（命中/登记/状态的读数）。
 *   ⇒ 与「块级指针化」同一个理由：本文件是**适配器**，本体由运行器经 `ctx.legacy.addrRecall`
 *     交进来，保证全项目**只有一套实现**（§2.2）。
 *
 * ── 契约（与别的算法完全一样）──────────────────────────────────────────────────
 *   `apply(B_msgs, ref, ctx) → { msgs, cover, n, ptr }`
 *   ⛔ A 与 C **根本没传进来** —— "装配只碰 B"是结构保证，不靠算法自觉。
 * ══════════════════════════════════════════════════════════════════════════════════════ */
import { register } from './registry.js';

export const AM_ADDR_RECALL_ID = 'am-addr-recall';

register({
    id: AM_ADDR_RECALL_ID,
    name: '区间唤起',
    version: 'v1',
    /* ★ v6.41.4：与"块级指针化"同一条元数据 —— 本体在主链路里，只有主链跑得动它。 */
    needs: 'legacy',
    desc: '把 B 区正文里**真发出去过的连续区间**按最长匹配换成 `<AMxxxx/>`；'
        + '没命中的字节、以及块新长出来的尾巴照原文发 ⇒ "上一版用指针唤起、新长的尾巴原文发"。'
        + '只做一层：遇到指针整段跳过（指针里绝不套指针）。'
        + '（本体是客户端既有实现，由运行器经 `ctx.legacy.addrRecall` 交进来 —— 全项目只有这一套实现。）',
    apply(B_msgs, ref, ctx) {
        const fn = ctx && ctx.legacy && ctx.legacy.addrRecall;
        if (typeof fn !== 'function') {
            throw new Error('区间唤起：这一级的本体住在**主链路**里（它要用那一轮的跨轮台账：区间地址池 / 命中读数），'
                + '**只有主链跑得动它** —— 面板这条"只读切片复算"链没有那套台账，所以这一级在面板上算不了（如实报，不假装算过）');
        }
        const msgs = fn(B_msgs);
        if (!Array.isArray(msgs) || msgs.length !== (B_msgs || []).length) {
            throw new Error('区间唤起：出来条数与进来对不上（契约要求"进来几条、出去几条"）');
        }
        /* ⚠ 读数不在这里编：省字账在 `_amAddrSaved` 上，只有本体知道怎么算 ⇒ 这里交 0，
         *   运行器以本体记的账为准。 */
        return { msgs, cover: 0, n: 0, ptr: 0 };
    },
});
