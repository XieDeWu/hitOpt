/* ══════════════════════════════════════════════════════════════════════════════════════
 * 算法：**块级指针化**（`core/expAlgo/amBlockPtr.js`）
 *
 *   id `am-block-ptr` ｜ 名字「块级指针化」｜ 版本 `v1`
 *
 * ── 它是什么（用户 2026-09-20 定版：算法组合管线）─────────────────────────────────
 *   管线里的一级：把 B 区里**配对标签的顶层块**换成指针壳 —— 发过的块只发编号
 *   （`<HASH-xxxxxx name="tag"/>`），首次注入的块走包裹壳（`<HASH-xxxxxx>原文</HASH-xxxxxx>`）。
 *   它是 Horae 最早那两层里的**第一层**，从 v6.20 起就在主链路上跑。
 *
 * ── 为什么这个文件里没有算法本体（**如实写，不冒充模块化**）────────────────────────
 *   本体是客户端 `_abSplit` 里那段（`_amPtr` ＋ 块级那一次 `B.map`），它依赖**跨轮状态**：
 *     `_amPoolSend`（已发块指纹池，从 localStorage 装回来）、`_amBlocks`（栈式配对）、
 *     `_pfHash` / `_amPtrId`（唯一生成点）、`_inKeepZone`（保真区判定）。
 *   那些东西**住在主链路里、每轮都在变**，搬出来就要连跨轮台账一起搬 —— 那是另一件事
 *   （本项目有"一处算法只许有一套实现"的纪律，§2.2：宁可留一个适配器，也不许出现两份实现互相漂移）。
 *   ⇒ 本文件是**适配器**：运行器把本体从 `ctx.legacy.blockPtr` 交进来，这里只声明
 *     "我是管线里的一级、我叫什么、我按契约收 B 吐 B"。
 *   ⚠ 这一段是**如实标注**，不是"模块化完成了"的宣称；本体搬家是后续独立的一步。
 *
 * ── 契约（与别的算法完全一样）──────────────────────────────────────────────────
 *   `apply(B_msgs, ref, ctx) → { msgs, cover, n, ptr }`
 *     · `B_msgs`：这一级要处理的 B 区（**只读，不改原对象**）
 *     · `ref`   ：参考串（上文那一份；这一级用不到 —— 块级判据问的是跨轮指纹池，不是 ref）
 *     · `ctx`   ：运行器交进来的运行时上下文（`legacy` 里是本体的唯一实现）
 *   ⛔ A 与 C **根本没传进来**（用户指令 A 的落地方式：不是"算法自觉不动"，而是**够不到**）。
 * ══════════════════════════════════════════════════════════════════════════════════════ */
import { register } from './registry.js';

export const AM_BLOCK_PTR_ID = 'am-block-ptr';

register({
    id: AM_BLOCK_PTR_ID,
    name: '块级指针化',
    version: 'v1',
    /* ★ v6.41.4【元数据：这一级跑起来依赖"主链路那一轮的台账"】—— 面板据此**如实标注**"主链专属"，
       而不是让用户点下去、再看到一片空白。判据是这个字段，不是"id 是不是 am- 开头"（那是开小灶）。 */
    needs: 'legacy',
    desc: '把 B 区里**配对标签的顶层块**换成指针壳：发过的块只发编号（`<HASH-xxxxxx name="tag"/>`），'
        + '首次注入的块走包裹壳（`<HASH-xxxxxx>原文</HASH-xxxxxx>`）；同一层互不重叠、指针里绝不套指针。'
        + '（本体是客户端既有实现，由运行器经 `ctx.legacy.blockPtr` 交进来 —— 全项目只有这一套实现。）',
    apply(B_msgs, ref, ctx) {
        const fn = ctx && ctx.legacy && ctx.legacy.blockPtr;
        if (typeof fn !== 'function') {
            throw new Error('块级指针化：这一级的本体住在**主链路**里（它要用那一轮的跨轮台账：已发块指纹池 / 包装账），'
                + '**只有主链跑得动它** —— 面板这条"只读切片复算"链没有那套台账，所以这一级在面板上算不了（如实报，不假装算过）');
        }
        const msgs = fn(B_msgs);
        if (!Array.isArray(msgs) || msgs.length !== (B_msgs || []).length) {
            throw new Error('块级指针化：出来条数与进来对不上（契约要求"进来几条、出去几条"）');
        }
        /* ⚠ 读数不在这里编：`cover/n/ptr` 由运行器从主链路那套记账里取（块级的省字账在
         *   `_amSave` / `_amN` / `_amPtrChars` 上，那三个量只有本体知道怎么算）。
         *   ⇒ 这里如实交 0，运行器会以本体记的账为准。 */
        return { msgs, cover: 0, n: 0, ptr: 0 };
    },
});
